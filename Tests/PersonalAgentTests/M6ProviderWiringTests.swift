import Foundation
import Testing
import PAKernel
import PAProviders
import PAComposition

@Suite("M6 Provider Wiring")
struct M6ProviderWiringTests {
    private struct ExplicitAllowPolicy: PolicyEvaluating {
        func evaluate(_ intent: ActionIntent) async -> PolicyDecision {
            .allow("test grant")
        }
    }

    @Test("canonical M6 composition uses the configured provider for reasoning")
    func configuredProviderDrivesReasoning() async throws {
        let expected = "answer generated by configured provider"
        let provider = DeterministicFakeProvider(
            script: .success(
                LLMResponse(
                    text: expected,
                    finishReason: "stop",
                    model: ModelID(rawValue: "fake-text")
                )
            )
        )
        let root = try await M6CompositionRoot(
            provider: provider,
            policy: ExplicitAllowPolicy()
        )
        let goal = Goal(statement: "What is the test answer?")
        try await root.runtime.submit(goal: goal)

        let evaluation = try await root.orchestrator.run(goalID: goal.id)

        #expect(evaluation.reason == expected)
    }
}
